"use client";

import { Check, Copy, Download, ShieldCheck, TriangleAlert } from "lucide-react";
import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";

/** What the person adds to their authenticator app: a QR code, or the key to type in. */
export function SecretPanel({ qr, secret }: { qr: string; secret: string }) {
  const [copied, setCopied] = useState(false);
  // Groups of four are easier to read aloud and to type; the app ignores spaces.
  const groups = secret.match(/.{1,4}/g) ?? [secret];

  return (
    <div className="flex flex-col items-center gap-3 sm:flex-row sm:items-start">
      {qr && (
        // Not next/image: this is a data URL generated by our own server.
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={qr}
          alt="QR code to scan with your authenticator app"
          width={176}
          height={176}
          className="size-44 shrink-0 rounded-md border border-border bg-white p-1"
        />
      )}
      <div className="min-w-0 text-center sm:text-left">
        <p className="text-xs text-fg-muted">Can&apos;t scan? Enter this key in your app instead:</p>
        <p className="mt-1 font-mono text-sm font-medium tracking-wide text-fg" data-testid="two-factor-secret">
          {/* Each group stays whole, so the key wraps between groups, never inside one. */}
          {groups.map((group, index) => (
            <span key={index} className="mr-2 inline-block">
              {group}
            </span>
          ))}
        </p>
        <Button
          variant="ghost"
          size="sm"
          className="mt-1 -ml-2"
          onClick={() => {
            void navigator.clipboard?.writeText(secret).then(() => {
              setCopied(true);
              setTimeout(() => setCopied(false), 1500);
            });
          }}
        >
          {copied ? <Check /> : <Copy />}
          {copied ? "Copied" : "Copy key"}
        </Button>
      </div>
    </div>
  );
}

/** Six digits from the app. Numeric keyboard on phones, and the browser may offer to fill it. */
export function CodeField({
  id,
  label,
  value,
  onChange,
  allowRecovery = false,
  autoFocus,
}: {
  id: string;
  label: string;
  value: string;
  onChange: (value: string) => void;
  /** Also accepts a recovery code, so the field must take letters and a dash. */
  allowRecovery?: boolean;
  autoFocus?: boolean;
}) {
  return (
    <div className="space-y-1.5">
      <Label htmlFor={id}>{label}</Label>
      <Input
        id={id}
        value={value}
        onChange={(event) => onChange(event.target.value)}
        inputMode={allowRecovery ? "text" : "numeric"}
        autoComplete="one-time-code"
        autoFocus={autoFocus}
        spellCheck={false}
        maxLength={allowRecovery ? 16 : 7}
        placeholder={allowRecovery ? "123456 or recovery code" : "123456"}
        className="h-9 font-mono tracking-widest"
      />
    </div>
  );
}

/**
 * The one-time recovery codes. They are the only way in if the phone is lost, and
 * cannot be shown again — so this insists on being acknowledged before it closes.
 */
export function RecoveryCodes({ codes, onDone, doneLabel = "Done" }: { codes: string[]; onDone: () => void; doneLabel?: string }) {
  const [saved, setSaved] = useState(false);
  const [copied, setCopied] = useState(false);
  const text = codes.join("\n");

  return (
    <div className="space-y-3">
      <div className="flex items-start gap-2 rounded-md border border-border bg-surface-subtle p-3 text-xs text-fg-muted">
        <TriangleAlert className="mt-0.5 size-4 shrink-0 text-warning" aria-hidden />
        <p>
          Keep these somewhere safe. Each one signs you in once if you lose your phone, and{" "}
          <span className="font-medium text-fg">they will not be shown again</span>.
        </p>
      </div>
      <ul className="grid grid-cols-2 gap-x-4 gap-y-1.5 rounded-md border border-border bg-surface p-3 font-mono text-sm text-fg" data-testid="recovery-codes">
        {codes.map((code) => (
          <li key={code}>{code}</li>
        ))}
      </ul>
      <div className="flex flex-wrap gap-2">
        <Button
          variant="secondary"
          size="sm"
          onClick={() => {
            void navigator.clipboard?.writeText(text).then(() => {
              setCopied(true);
              setTimeout(() => setCopied(false), 1500);
            });
          }}
        >
          {copied ? <Check /> : <Copy />}
          {copied ? "Copied" : "Copy"}
        </Button>
        <Button
          variant="secondary"
          size="sm"
          onClick={() => {
            const url = URL.createObjectURL(new Blob([`Helix recovery codes\n\n${text}\n`], { type: "text/plain" }));
            const link = document.createElement("a");
            link.href = url;
            link.download = "helix-recovery-codes.txt";
            link.click();
            URL.revokeObjectURL(url);
          }}
        >
          <Download />
          Download
        </Button>
      </div>
      <label className="flex items-center gap-2 text-sm text-fg">
        <input type="checkbox" checked={saved} onChange={(event) => setSaved(event.target.checked)} className="size-4 accent-[var(--accent)]" />
        I have saved these codes
      </label>
      <Button variant="primary" size="sm" disabled={!saved} onClick={onDone}>
        <ShieldCheck />
        {doneLabel}
      </Button>
    </div>
  );
}
